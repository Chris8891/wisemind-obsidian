import {computed, inject, type InjectionKey, provide, ref, watch} from 'vue';
import {useI18n} from 'vue-i18n';
import {Notice} from 'obsidian';

import {usePlugin} from '../../../composables/usePlugin';
import {type AudioInputDevice, listAudioInputDevices} from '../../../services/audioCapture';
import {
  classifyTranscriptionAvailabilityError,
  isTranscriptionVersionSupported,
  type TranscriptionAvailabilityStatus,
} from '../../../services/transcriptionAvailability';
import type {TranscriptionScene, TranscriptionStartOptions} from '../../../types';

import {formatRecordDate} from './format';
import type {ActiveMarkdownFile} from './useActiveMarkdownFile';
import {useMicrophoneTest} from './useMicrophoneTest';

/** Start form, provider/microphone options and the availability check for a new recording. */
function useTranscriptionSetup({activeMarkdownPath, refreshActiveFile}: ActiveMarkdownFile) {
  const plugin = usePlugin();
  const {t} = useI18n();
  const controller = plugin.transcription;

  const createDefaultRecordTitle = (time = Date.now()) =>
    t('transcription.defaultRecordTitle', {date: formatRecordDate(time)});
  const initialRecordTitle = createDefaultRecordTitle();
  let autoGeneratedTitle = initialRecordTitle;

  const startOptions = ref<TranscriptionStartOptions | null>(null);
  const audioDevices = ref<AudioInputDevice[]>([]);
  const setupStatus = ref<'checking' | 'ready' | TranscriptionAvailabilityStatus>('checking');
  const loading = ref(false);
  const starting = ref(false);
  const form = ref({
    title: initialRecordTitle,
    scene: plugin.settings.transcription.defaultScene as TranscriptionScene,
    providerId: plugin.settings.transcription.defaultProviderId,
    deviceId: plugin.settings.transcription.defaultMicrophoneId,
    saveAudio: plugin.settings.transcription.saveAudio,
    speakerDiarization: false,
    speakerCount: '0',
    liveWriteToNote: false,
  });

  const quotaText = computed(() => {
    const membership = startOptions.value?.membership;
    if (!membership?.canStart) return '';
    const session = membership.sessionLimitMinutes;
    if (membership.monthlyRemainingMs !== null) {
      return t('transcription.quotaRemaining', {
        remaining: Math.max(0, Math.floor(membership.monthlyRemainingMs / 60_000)),
        session: session ?? t('transcription.unlimited'),
      });
    }
    if (session !== null) return t('transcription.quotaSessionOnly', {minutes: session});
    return t('transcription.quotaUnlimited');
  });
  const canStart = computed(() =>
    Boolean(
      startOptions.value?.membership.canStart &&
        form.value.providerId &&
        (!form.value.liveWriteToNote || activeMarkdownPath.value) &&
        !starting.value &&
        !loading.value,
    ),
  );
  const startBlockedReason = computed(() => {
    const options = startOptions.value;
    if (!options || loading.value || starting.value) return '';
    if (!options.providers.length) return t('transcription.noProvider');
    if (!options.membership.canStart) return t('transcription.quotaUnavailable');
    if (!form.value.providerId) return t('transcription.chooseProvider');
    if (form.value.liveWriteToNote && !activeMarkdownPath.value) {
      return t('transcription.liveWriteNeedsNote');
    }
    return '';
  });
  const providerOptions = computed(() =>
    (startOptions.value?.providers || []).map(provider => ({
      value: provider.id,
      label: `${provider.name}${provider.modelName ? ` · ${provider.modelName}` : ''}`,
    })),
  );
  const currentProvider = computed(() =>
    startOptions.value?.providers.find(provider => provider.id === form.value.providerId),
  );
  const speakerCountOptions = computed(() => [
    {value: '0', label: t('transcription.speakerCountAuto')},
    ...Array.from({length: 9}, (_, index) => ({
      value: String(index + 2),
      label: t('transcription.speakerCountValue', {count: index + 2}),
    })),
  ]);
  const microphoneOptions = computed(() => {
    const options = audioDevices.value.map((device, index) => ({
      value: device.deviceId,
      label: device.label || t('transcription.microphoneNumber', {number: index + 1}),
    }));
    if (!options.some(option => option.value === 'default')) {
      options.unshift({value: 'default', label: t('transcription.defaultMicrophone')});
    }
    return options;
  });

  const handleLiveWriteToggle = (enabled: boolean) => {
    if (!enabled) {
      form.value.liveWriteToNote = false;
      refreshActiveFile();
      return;
    }
    const currentNote = refreshActiveFile();
    if (!currentNote) {
      form.value.liveWriteToNote = false;
      new Notice(t('transcription.liveWriteNeedsNoteNotice'));
      return;
    }
    form.value.liveWriteToNote = true;
  };

  // A refresh from the ready form keeps the form on screen instead of flashing the checking view.
  const loadSetup = async (requestMicrophonePermission = false) => {
    loading.value = true;
    if (setupStatus.value !== 'ready') setupStatus.value = 'checking';
    try {
      const health = await plugin.api.health();
      if (!isTranscriptionVersionSupported(health.appVersion)) {
        startOptions.value = null;
        setupStatus.value = 'unsupported';
        return false;
      }
      const options = await plugin.api.getTranscriptionStartOptions();
      startOptions.value = options;
      setupStatus.value = 'ready';
      if (
        !form.value.providerId ||
        !options.providers.some(item => item.id === form.value.providerId)
      ) {
        form.value.providerId = options.activeProviderId || options.providers[0]?.id || '';
      }

      try {
        const devices = await listAudioInputDevices(requestMicrophonePermission);
        audioDevices.value = devices;
        if (
          form.value.deviceId !== 'default' &&
          !devices.some(device => device.deviceId === form.value.deviceId)
        ) {
          form.value.deviceId = 'default';
        }
      } catch (error: any) {
        new Notice(error?.message || t('transcription.microphoneLoadFailed'));
        return false;
      }
      return true;
    } catch (error: unknown) {
      startOptions.value = null;
      setupStatus.value = classifyTranscriptionAvailabilityError(error);
      return false;
    } finally {
      loading.value = false;
    }
  };

  const microphoneTest = useMicrophoneTest({
    prepare: () => loadSetup(true),
    deviceId: () => form.value.deviceId,
  });

  const start = async () => {
    if (!canStart.value) return;
    const liveTargetFile = form.value.liveWriteToNote ? refreshActiveFile() : null;
    if (form.value.liveWriteToNote && !liveTargetFile) {
      form.value.liveWriteToNote = false;
      new Notice(t('transcription.liveWriteNeedsNoteNotice'));
      return;
    }
    starting.value = true;
    // The microphone test holds its own capture; release it before the real recording grabs the device.
    microphoneTest.stop();
    try {
      if (!form.value.title.trim() || form.value.title.trim() === autoGeneratedTitle) {
        autoGeneratedTitle = createDefaultRecordTitle();
        form.value.title = autoGeneratedTitle;
      }
      plugin.settings.transcription.defaultScene = form.value.scene;
      plugin.settings.transcription.defaultProviderId = form.value.providerId;
      plugin.settings.transcription.defaultMicrophoneId = form.value.deviceId;
      plugin.settings.transcription.saveAudio = form.value.saveAudio;
      await plugin.saveSettings();
      await controller.start({
        title: form.value.title.trim() || undefined,
        scenario: form.value.scene,
        providerId: form.value.providerId,
        deviceId: form.value.deviceId,
        saveAudio: form.value.saveAudio,
        speakerDiarization: form.value.speakerDiarization,
        speakerCount: Number(form.value.speakerCount || 0),
        targetPath: liveTargetFile?.path || activeMarkdownPath.value,
        liveWriteToNote: form.value.liveWriteToNote,
      });
    } catch (error: any) {
      new Notice(error?.message || t('transcription.startFailed'));
    } finally {
      starting.value = false;
    }
  };

  /** Fresh auto title and live writing off, ready for the next recording. */
  const resetForm = () => {
    autoGeneratedTitle = createDefaultRecordTitle();
    form.value.title = autoGeneratedTitle;
    form.value.liveWriteToNote = false;
  };

  watch(activeMarkdownPath, path => {
    if (!path) form.value.liveWriteToNote = false;
  });

  watch(currentProvider, provider => {
    if (!provider?.supportsSpeakerDiarization) {
      form.value.speakerDiarization = false;
      form.value.speakerCount = '0';
    }
  });

  return {
    activeMarkdownPath,
    form,
    startOptions,
    setupStatus,
    loading,
    starting,
    quotaText,
    canStart,
    startBlockedReason,
    providerOptions,
    currentProvider,
    speakerCountOptions,
    microphoneOptions,
    microphoneTest,
    handleLiveWriteToggle,
    loadSetup,
    start,
    resetForm,
  };
}

export type TranscriptionSetup = ReturnType<typeof useTranscriptionSetup>;

const transcriptionSetupKey: InjectionKey<TranscriptionSetup> = Symbol('transcriptionSetup');

/** Creates the page-level setup state (it outlives the idle view) and shares it with child views. */
export function provideTranscriptionSetup(activeNote: ActiveMarkdownFile) {
  const setup = useTranscriptionSetup(activeNote);
  provide(transcriptionSetupKey, setup);
  return setup;
}

export function injectTranscriptionSetup() {
  const setup = inject(transcriptionSetupKey);
  if (!setup) throw new Error('Transcription setup is not provided');
  return setup;
}
